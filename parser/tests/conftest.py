def _find_cyrillic_font_path() -> Path:
    candidates = (
        Path("/System/Library/Fonts/Supplemental/Arial Unicode.ttf"),
        Path("/System/Library/Fonts/Supplemental/Arial.ttf"),
        Path("/Library/Fonts/Arial Unicode.ttf"),
        Path("/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf"),
        Path("/usr/share/fonts/dejavu/DejaVuSans.ttf"),
    )
    for candidate in candidates:
        if candidate.exists():
            return candidate
    raise FileNotFoundError("No Cyrillic-capable TTF font found for synthetic PDF fixtures")


def _ensure_font_registered() -> str:
    pdfmetrics = cast(Any, import_module("reportlab.pdfbase.pdfmetrics"))
    ttfonts = cast(Any, import_module("reportlab.pdfbase.ttfonts"))
    font_name = "SyntheticFixtureFont"
    registered = cast(tuple[str, ...], pdfmetrics.getRegisteredFontNames())
    if font_name not in registered:
        pdfmetrics.registerFont(ttfonts.TTFont(font_name, str(_find_cyrillic_font_path())))
    return font_name


def _write_pdf(path: Path, pages: tuple[tuple[str, ...], ...]) -> None:
    canvas_module = cast(Any, import_module("reportlab.pdfgen.canvas"))
    pagesizes = cast(Any, import_module("reportlab.lib.pagesizes"))
    font_name = _ensure_font_registered()

    pdf = canvas_module.Canvas(str(path), pagesize=pagesizes.A4)
    _, page_height = cast(tuple[float, float], pagesizes.A4)
    for lines in pages:
        text = pdf.beginText(40, page_height - 40)
        text.setFont(font_name, 10)
        for line in lines:
            text.textLine(line)
        pdf.drawText(text)
        pdf.showPage()
    pdf.save()


